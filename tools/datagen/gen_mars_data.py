#!/usr/bin/env python3
"""Generate the Mars dimension's datapack JSON (src/main/resources/data/...).

These files are generated by script (rather than hand-written) so the sol timeline stays consistent with the
24,660-tick period, the biome feature lists keep one canonical order (26.3's FeatureSorter rejects conflicting
orders), and every number traces to a single place. Values are documented in docs/SCIENCE.md.

Run: python3 tools/datagen/gen_mars_data.py
"""

from __future__ import annotations

import json
import math
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DATA = REPO / "src/main/resources/data"

SOL = 24660                     # ticks per sol (88,775.244 s at 3.6 s per tick)
NOON = SOL // 4                 # vanilla convention: tick 0 = 06:00, noon a quarter period later
SUNSET = SOL // 2
DATUM_Y = 192
MIN_Y = 0
HEIGHT = 448

# --- planet parameters (docs/SCIENCE.md) ------------------------------------------------------------------
GRAVITY = 0.3794                # 3.721 / 9.80665 (effective mean incl. rotation; NSSDCA 3.73 GM/R^2)
PRESSURE_PA = 560.0             # annual-mean pressure at the MOLA zero level (SCIENCE.md section 3)
SCALE_HEIGHT_M = 11000.0        # NSSDCA
# Density at the datum from the ideal-gas law, relative to Earth's sea-level 1.225 kg/m3:
# rho = p M / (R T) with M = 43.34 g/mol and T = 210 K gives 0.0139 kg/m3 (NSSDCA: 0.016 +- 0.006 at 636 Pa).
AIR_DENSITY = round(PRESSURE_PA * 0.04334 / (8.314462618 * 210.0) / 1.225, 5)
RADIATION_MSV_PER_DAY = 0.64    # Curiosity RAD, Gale crater surface (Hassler et al. 2014)
SOUND_DAMPING = 0.7             # gain x0.3 (-10.5 dB); reality is ~-20 dB (Maurice et al. 2022), a compromise

# Colours (tuned against Curiosity/Perseverance true-colour images; see SCIENCE.md "Sky")
SKY_DAY = "#b98a63"             # butterscotch zenith
FOG_DAY = "#cfa27a"             # brighter, dustier horizon
SUNSET_BLUE = (0x6f, 0x9f, 0xe0)


def write(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        json.dump(obj, f, indent=2)
        f.write("\n")


def argb(alpha: float, rgb) -> str:
    a = max(0, min(255, round(alpha * 255)))
    return "#%02x%02x%02x%02x" % (a, rgb[0], rgb[1], rgb[2])


