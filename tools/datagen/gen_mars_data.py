SCALE_HEIGHT_M = 11000.0        # NSSDCA
# Density at the datum from the ideal-gas law, relative to Earth's sea-level 1.225 kg/m3:
# rho = p M / (R T) with M = 43.34 g/mol and T = 210 K gives 0.0139 kg/m3 (NSSDCA: 0.016 +- 0.006 at 636 Pa).
