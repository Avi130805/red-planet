def main() -> None:
    write(DATA / "redplanet/dimension_type/mars.json", dimension_type())
    write(DATA / "redplanet/world_clock/mars.json", {})
    write(DATA / "redplanet/timeline/mars_day.json", sol_timeline())
    write(DATA / "redplanet/tags/timeline/in_mars.json", {"values": ["redplanet:mars_day"]})
    write(DATA / "redplanet/worldgen/density_function/mars/surface_height.json",
          {"type": "minecraft:cache", "input": {"type": "redplanet:mars_height"}})
    write(DATA / "redplanet/worldgen/noise_settings/mars.json", noise_settings())
    for name, (temp, attrs) in BIOMES.items():
        write(DATA / f"redplanet/worldgen/biome/{name}.json", biome(name, temp, attrs))
    write(DATA / "redplanet/tags/worldgen/biome/is_mars.json", {"values": [f"redplanet:{n}" for n in BIOMES]})
    write(DATA / "redplanet/dimension/mars.json", {
        "type": "redplanet:mars",
        "generator": {
            "type": "minecraft:noise",
            "settings": "redplanet:mars",
            "biome_source": {"type": "redplanet:mars", "biomes": {n: f"redplanet:{n}" for n in BIOMES}},
        },
    })

    # Damage type: hypoxia (+ the same tags as vanilla drowning)
    write(DATA / "redplanet/damage_type/hypoxia.json",
          {"message_id": "redplanet.hypoxia", "scaling": "never", "exhaustion": 0.0, "effects": "drowning"})
    for tag in ("bypasses_armor", "bypasses_wolf_armor", "is_drowning", "no_impact", "no_knockback", "wither_immune_to"):
        write(DATA / f"minecraft/tags/damage_type/{tag}.json", {"replace": False, "values": ["redplanet:hypoxia"]})

    # Combustion and breathing tags
    write(DATA / "redplanet/tags/block/requires_oxygen.json", {"values": [
        "#minecraft:fire", "#minecraft:lanterns",
        "minecraft:torch", "minecraft:wall_torch", "minecraft:soul_torch", "minecraft:soul_wall_torch",
        {"id": "minecraft:copper_torch", "required": False}, {"id": "minecraft:copper_wall_torch", "required": False},
    ]})
    write(DATA / "redplanet/tags/block/extinguished_without_oxygen.json",
          {"values": ["#minecraft:campfires", "#minecraft:candles", "#minecraft:candle_cakes"]})
    write(DATA / "redplanet/tags/entity_type/does_not_breathe.json", {"values": [
        "#minecraft:undead", "minecraft:armor_stand", "minecraft:iron_golem", "minecraft:snow_golem",
        {"id": "minecraft:copper_golem", "required": False}, "minecraft:blaze", "minecraft:vex", "minecraft:allay",
        "minecraft:shulker", "minecraft:ender_dragon", "minecraft:enderman", "minecraft:endermite",
    ]})
    print("Mars data written under", DATA)


if __name__ == "__main__":
    main()
