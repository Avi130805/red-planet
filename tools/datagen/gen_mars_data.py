"""Generate the Mars dimension's datapack JSON (src/main/resources/data/...).

These files are generated by script (rather than hand-written) so the sol timeline stays consistent with the
24,660-tick period, the biome feature lists keep one canonical order (26.3's FeatureSorter rejects conflicting
orders), and every number traces to a single place. Values are documented in docs/SCIENCE.md.

Run: python3 tools/datagen/gen_mars_data.py
"""

