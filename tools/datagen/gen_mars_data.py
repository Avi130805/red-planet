def sol_timeline() -> dict:
    """The sol: vanilla's day structure stretched to 24,660 ticks, with Mars' longer twilight (high-altitude dust
    keeps scattering sunlight for up to ~2 h after sunset), darker nights (no large moon), and a blue glow around
    the setting/rising Sun (forward scattering by ~1.5 um dust)."""
    bezier = {"cubic_bezier": [0.362, 0.241, 0.638, 0.759]}
    day_start, day_end = 330, 12000           # full daylight between these
    night_start, night_end = 14400, 22300     # full night between these (twilight ~2,400 ticks)

    def daynight(day_value, night_value):
        return [
            {"ticks": day_start, "value": day_value},
            {"ticks": day_end, "value": day_value},
            {"ticks": night_start, "value": night_value},
            {"ticks": night_end, "value": night_value},
        ]

    # Sunrise/sunset glow: alpha envelope peaking just after the Sun crosses the horizon.
    glow = []
    for centre, sign in ((SUNSET, 1), (0, -1)):
        for k in range(-7, 10):
            t = centre + k * 200 * sign
            phase = (k * 200 - 250) / 800.0
            a = 0.85 * math.exp(-phase * phase)
            tt = t % SOL
            glow.append({"ticks": tt, "value": argb(a, SUNSET_BLUE)})
    glow.sort(key=lambda kf: kf["ticks"])
    # at most 2 keyframes per tick; dedupe by tick keeping the larger alpha
    dedup = {}
    for kf in glow:
        prev = dedup.get(kf["ticks"])
        if prev is None or int(kf["value"][1:3], 16) > int(prev["value"][1:3], 16):
            dedup[kf["ticks"]] = kf
    glow = [dedup[t] for t in sorted(dedup)]

    stars = [
        {"ticks": 600, "value": 0.0},
        {"ticks": 11700, "value": 0.0},
        {"ticks": 12900, "value": 0.25},
        {"ticks": 14000, "value": 0.85},
        {"ticks": 22600, "value": 0.85},
        {"ticks": 23700, "value": 0.25},
    ]

    return {
        "clock": "redplanet:mars",
        "period_ticks": SOL,
        "time_markers": {
            "minecraft:wake_up_from_sleep": 0,
            "minecraft:day": {"ticks": round(1000 * SOL / 24000), "show_in_commands": True},
            "minecraft:noon": {"ticks": NOON, "show_in_commands": True},
            "minecraft:night": {"ticks": round(13000 * SOL / 24000), "show_in_commands": True},
            "minecraft:midnight": {"ticks": round(18000 * SOL / 24000), "show_in_commands": True},
            "redplanet:sunset": {"ticks": SUNSET, "show_in_commands": True},
        },
        "tracks": {
            "minecraft:visual/sun_angle": {"ease": bezier, "keyframes": [{"ticks": NOON, "value": 360.0}, {"ticks": NOON, "value": 0.0}]},
            "minecraft:visual/star_angle": {"ease": bezier, "keyframes": [{"ticks": NOON, "value": 360.0}, {"ticks": NOON, "value": 0.0}]},
            "minecraft:visual/moon_angle": {"keyframes": [{"ticks": 0, "value": 180.0}]},
            "minecraft:gameplay/sky_light_level": {"modifier": "multiply", "keyframes": daynight(1.0, 0.2)},
            "minecraft:visual/sky_light_factor": {"modifier": "multiply", "keyframes": daynight(1.0, 0.16)},
            "minecraft:visual/sky_light_color": {"modifier": "multiply", "keyframes": daynight("#ffffff", "#68687e")},
            "minecraft:visual/sky_color": {"modifier": "multiply", "keyframes": daynight("#ffffff", "#000000")},
            "minecraft:visual/fog_color": {"modifier": "multiply", "keyframes": daynight("#ffffff", "#0d0d12")},
            "minecraft:visual/star_brightness": {"modifier": "maximum", "keyframes": stars},
            "minecraft:visual/sunrise_sunset_color": {"keyframes": glow},
        },
    }


